#!/usr/bin/env node

import { randomBytes } from "node:crypto";
import { spawnSync } from "node:child_process";
import { access, chmod, copyFile, mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import { constants } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { loadEnvFile } from "../src/env-file.mjs";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const command = args.shift() || "help";

function option(name, fallback = null) {
  const index = args.indexOf(name);
  if (index === -1) return fallback;
  const value = args[index + 1];
  if (!value || value.startsWith("--")) fail(`${name} needs a value`);
  args.splice(index, 2);
  return value;
}

function flag(name) {
  const index = args.indexOf(name);
  if (index === -1) return false;
  args.splice(index, 1);
  return true;
}

function homeDir() {
  return resolve(option("--dir", process.env.INSTAGRAM_CTA_HOME || process.cwd()));
}

function fail(message, code = 1) {
  console.error(`instagram-cta: ${message}`);
  process.exit(code);
}

function help() {
  console.log(`Instagram CTA Kit

Usage:
  instagram-cta init [--dir PATH] [--locale en|he] [--mode polling|webhook]
  instagram-cta doctor [--dir PATH] [--live]
  instagram-cta route add KEYWORD URL --campaign-id ID [route options]
  instagram-cta routes validate [--dir PATH] [--check-guides]
  instagram-cta start [--dir PATH]

Examples:
  npx github:dangogit/instagram-cta-kit init --locale en --mode polling
  npx github:dangogit/instagram-cta-kit doctor
  npx github:dangogit/instagram-cta-kit route add GUIDE https://example.com/guide --campaign-id first-guide
  npx github:dangogit/instagram-cta-kit start
`);
}

