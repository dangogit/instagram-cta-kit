async function init() {
  const home = homeDir();
  const locale = option("--locale", "en");
  const provider = option("--provider", "hookmyapp");
  const mode = option("--mode", provider === "hookmyapp" ? "webhook" : "polling");
  const force = flag("--force");
  if (!['en', 'he'].includes(locale)) fail("--locale must be en or he");
  if (!["hookmyapp", "meta"].includes(provider)) fail("--provider must be hookmyapp or meta");
  if (!['polling', 'webhook'].includes(mode)) fail("--mode must be polling or webhook");
  if (args.length) fail(`unknown arguments: ${args.join(" ")}`);

  await mkdir(resolve(home, "state"), { recursive: true, mode: 0o700 });
  const envPath = resolve(home, ".env");
  const routesPath = resolve(home, "routes.json");
  if (!force) {
    for (const path of [envPath, routesPath]) {
      try {
        await access(path, constants.F_OK);
        fail(`${path} already exists. Use --force to replace generated config.`);
      } catch (error) {
        if (error.code !== "ENOENT") throw error;
      }
    }
  }

  await writeFile(envPath, renderEnv({ locale, mode, provider }), { mode: 0o600 });
  await copyFile(resolve(packageRoot, "routes.example.json"), routesPath);
  await chmod(routesPath, 0o644);
  console.log(`Created Instagram CTA config in ${home}`);
  console.log("routes.json holds two example routes (GUIDE and מדריך) that point at example.com. They are placeholders, so guide checks skip them. Replace their URLs or run instagram-cta route remove GUIDE");
  if (provider === "hookmyapp") {
    console.log("Next: connect Instagram with hookmyapp, write its channel env into .env, add WEBHOOK_HMAC_SECRET, then run instagram-cta doctor");
  } else {
    console.log("Next: add your Meta app credentials to .env, edit routes.json, then run instagram-cta doctor");
  }
}

function isPlaceholder(value) {
  return !value || value.startsWith("replace-with-");
}

async function doctor() {
  const home = homeDir();
  const live = flag("--live");
  if (args.length) fail(`unknown arguments: ${args.join(" ")}`);
  const envPath = resolve(home, ".env");
  const loaded = await loadEnvFile(envPath);
  const checks = [];
  const add = (name, ok, detail) => checks.push({ name, ok, detail });

  add("Node.js", Number(process.versions.node.split(".")[0]) >= 20, process.versions.node);
  add(".env", Object.keys(loaded).length > 0, envPath);
  const dryRun = process.env.DRY_RUN === "1";
  const provider = process.env.CTA_PROVIDER
    || (process.env.INSTAGRAM_GRAPH_API_URL ? "hookmyapp" : "meta");
  add("provider", ["hookmyapp", "meta"].includes(provider), provider);
  const providerKeys = provider === "hookmyapp"
    ? [
      "INSTAGRAM_GRAPH_API_URL",
      "INSTAGRAM_ACCOUNT_ID",
      "INSTAGRAM_ACCESS_TOKEN",
      "HOOKMYAPP_CHANNEL_ID",
      "WEBHOOK_HMAC_SECRET",
    ]
    : ["META_APP_SECRET", "IG_USER_ID", "IG_ACCESS_TOKEN"];
  for (const key of [
    "VERIFY_TOKEN",
    "CTA_ADMIN_TOKEN",
    "CTA_ATTRIBUTION_SECRET",
    ...providerKeys,
  ]) {
    const configured = !isPlaceholder(process.env[key]);
    const allowedPlaceholder = dryRun && !["VERIFY_TOKEN", "CTA_ADMIN_TOKEN"].includes(key);
    add(key, configured || allowedPlaceholder, configured ? "configured" : allowedPlaceholder ? "placeholder allowed in dry run" : "missing");
  }
  if (provider === "hookmyapp") {
    const hookmyapp = spawnSync("hookmyapp", ["--version"], { encoding: "utf8" });
    add(
      "HookMyApp CLI",
      hookmyapp.status === 0 || dryRun,
      hookmyapp.status === 0
        ? hookmyapp.stdout.trim()
        : "not installed, required only to connect or manage the channel",
    );
  }

  const routesPath = resolve(home, process.env.ROUTES_FILE || "routes.json");
  try {
    const parsed = JSON.parse(await readFile(routesPath, "utf8"));
    add("routes.json", Array.isArray(parsed.routes) && parsed.routes.length > 0, `${parsed.routes?.length || 0} routes`);
  } catch (error) {
    add("routes.json", false, error.message);
  }

  try {
    const stateDir = resolve(home, dirname(process.env.STATE_FILE || "state/events.jsonl"));
    await mkdir(stateDir, { recursive: true });
    const probe = resolve(stateDir, `.write-test-${process.pid}`);
    await writeFile(probe, "ok", { mode: 0o600 });
    await unlink(probe);
    add("state directory", true, stateDir);
  } catch (error) {
    add("state directory", false, error.message);
  }

  const validation = runScript("scripts/validate-routes.mjs", [], home, {
    CHECK_GUIDES: live ? "1" : "0",
  });
  add("route validation", validation.status === 0, validation.status === 0 ? "passed" : "failed");

  const accessToken = process.env.INSTAGRAM_ACCESS_TOKEN || process.env.IG_ACCESS_TOKEN;
  const accountId = process.env.INSTAGRAM_ACCOUNT_ID || process.env.IG_USER_ID;
  if (live && !isPlaceholder(accessToken) && !isPlaceholder(accountId)) {
    try {
      const base = (
        process.env.INSTAGRAM_GRAPH_API_URL
        || process.env.GRAPH_BASE_URL
        || "https://graph.instagram.com/v25.0"
      ).replace(/\/$/, "");
      const response = await fetch(`${base}/${encodeURIComponent(accountId)}?fields=id,username`, {
        headers: { Authorization: `Bearer ${accessToken}` },
        signal: AbortSignal.timeout(8000),
      });
      add("Instagram credentials", response.ok, response.ok ? "account reachable" : `HTTP ${response.status}`);
    } catch (error) {
      add("Instagram credentials", false, error.message);
    }
  }

  for (const check of checks) console.log(`${check.ok ? "✓" : "✗"} ${check.name}: ${check.detail}`);
  if (checks.some((check) => !check.ok)) process.exitCode = 1;
}

// spawnSync reports a missing cwd as a bare ENOENT, so check it first.
async function ensureHome(home) {
  try {
    await access(home, constants.F_OK);
  } catch {
    fail(`${home} does not exist. Run instagram-cta init --dir ${home} first.`);
  }
}

function runScript(relativePath, scriptArgs, home, extraEnv = {}) {
  return spawnSync(process.execPath, [resolve(packageRoot, relativePath), ...scriptArgs], {
    cwd: home,
    env: {
      ...process.env,
      ...extraEnv,
      ROUTES_FILE: resolve(home, process.env.ROUTES_FILE || "routes.json"),
      STATE_FILE: resolve(home, process.env.STATE_FILE || "state/events.jsonl"),
    },
    stdio: "inherit",
  });
}

const ROUTE_SCRIPTS = {
  add: "scripts/add-route.mjs",
  remove: "scripts/remove-route.mjs",
};

async function route() {
  const subcommand = args.shift();
  const script = ROUTE_SCRIPTS[subcommand];
  if (!script) fail("use: instagram-cta route add KEYWORD URL --campaign-id ID, or instagram-cta route remove KEYWORD");
  const home = homeDir();
  await ensureHome(home);
  await loadEnvFile(resolve(home, ".env"));
  const result = runScript(script, args, home);
  if (result.error) fail(result.error.message);
  process.exitCode = result.status ?? 1;
}

async function routes() {
  const subcommand = args.shift();
  if (subcommand !== "validate") fail("use: instagram-cta routes validate");
  const home = homeDir();
  const checkGuides = flag("--check-guides");
  if (args.length) fail(`unknown arguments: ${args.join(" ")}`);
  await ensureHome(home);
  await loadEnvFile(resolve(home, ".env"));
  const result = runScript("scripts/validate-routes.mjs", [], home, {
    CHECK_GUIDES: checkGuides ? "1" : "0",
  });
  if (result.error) fail(result.error.message);
  process.exitCode = result.status ?? 1;
}

async function loadRuntime(home) {
  await loadEnvFile(resolve(home, ".env"));
  const host = ["0.0.0.0", "::"].includes(process.env.HOST) ? "127.0.0.1" : (process.env.HOST || "127.0.0.1");
  const port = Number(process.env.PORT || 18787);
  return {
    base: `http://${host}:${port}`,
    token: process.env.CTA_ADMIN_TOKEN || "",
  };
}

async function requestRuntime(path, { method = "GET", body = null, admin = false } = {}) {
  const home = homeDir();
  if (args.length) fail(`unknown arguments: ${args.join(" ")}`);
  const runtime = await loadRuntime(home);
  const headers = {};
  if (admin) {
    if (isPlaceholder(runtime.token)) fail("CTA_ADMIN_TOKEN is missing");
    headers.Authorization = `Bearer ${runtime.token}`;
  }
  if (body !== null) headers["Content-Type"] = "application/json";
  let response;
  try {
    response = await fetch(`${runtime.base}${path}`, {
      method,
      headers,
      ...(body !== null ? { body: JSON.stringify(body) } : {}),
      signal: AbortSignal.timeout(10_000),
    });
  } catch (error) {
    fail(`runtime is unreachable at ${runtime.base}: ${error.message}`);
  }
  const text = await response.text();
  let data;
  try {
    data = JSON.parse(text);
  } catch {
    data = { ok: false, error: text || `HTTP ${response.status}` };
  }
  console.log(JSON.stringify(data, null, 2));
  if (!response.ok) process.exitCode = 1;
  return data;
}

async function status() {
  const data = await requestRuntime("/health");
  if (data.ok === false) process.exitCode = 1;
}

async function dashboard() {
  const home = homeDir();
  const noOpen = flag("--no-open");
  if (args.length) fail(`unknown arguments: ${args.join(" ")}`);
  const runtime = await loadRuntime(home);
  if (isPlaceholder(runtime.token)) {
    fail("CTA_ADMIN_TOKEN is missing - run instagram-cta init first");
  }
  const url = `${runtime.base}/dashboard?token=${encodeURIComponent(runtime.token)}`;
  console.log(url);
  if (!noOpen) {
    const opener = process.platform === "darwin"
      ? "open"
      : process.platform === "win32" ? "start" : "xdg-open";
    spawnSync(opener, [url], {
      stdio: "ignore",
      shell: process.platform === "win32",
    });
  }
}

async function recover() {
  await requestRuntime("/admin/recover", { method: "POST", admin: true });
}

async function deadLetter() {
  const subcommand = args.shift();
  if (subcommand === "list") {
    await requestRuntime("/admin/dead-letter", { admin: true });
    return;
  }
  const eventKey = args.shift();
  if (!/^[a-f0-9]{64}$/.test(eventKey || "")) {
    fail("dead-letter retry and resolve require a 64-character EVENT_KEY");
  }
  if (subcommand === "retry") {
    await requestRuntime(`/admin/dead-letter/${eventKey}/retry`, {
      method: "POST",
      admin: true,
    });
    return;
  }
  if (subcommand === "resolve") {
    const reason = option("--reason");
    if (!reason) fail("dead-letter resolve requires --reason TEXT");
    await requestRuntime(`/admin/dead-letter/${eventKey}/resolve`, {
      method: "POST",
      body: { reason },
      admin: true,
    });
    return;
  }
  fail("use: instagram-cta dead-letter list|retry|resolve");
}

async function start() {
  const home = homeDir();
  if (args.length) fail(`unknown arguments: ${args.join(" ")}`);
  await loadEnvFile(resolve(home, ".env"));
  process.env.INSTAGRAM_CTA_HOME = home;
  const serverModule = await import(pathToFileURL(resolve(packageRoot, "src/server.mjs")).href);
  await serverModule.startServer();
}

switch (command) {
  case "init": await init(); break;
  case "doctor": await doctor(); break;
  case "route": await route(); break;
  case "routes": await routes(); break;
  case "status": await status(); break;
  case "dashboard": await dashboard(); break;
  case "recover": await recover(); break;
  case "dead-letter": await deadLetter(); break;
  case "start": await start(); break;
  case "help":
  case "--help":
  case "-h": help(); break;
  default: fail(`unknown command: ${command}. Run instagram-cta help.`);
}
